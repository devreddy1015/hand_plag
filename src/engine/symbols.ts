/** Is there a pen-drawn glyph for this character? */
export function hasSymbol(unit: string): boolean {
  const key = SAME_AS[unit] ?? unit;
  return key in DEFS;
}

const cache = new Map<string, StrokeGlyph | null>();

/**
 * The pen-drawn glyph for a character, fitted to a hand whose x-height and
 * capital height are `xHeight` and `capHeight` (fractions of the font size),
 * or null when there is none. Hands differ in how tall their capitals are
 * against their small letters, so the two zones are fitted separately.
 */
export function symbolGlyph(unit: string, xHeight: number, capHeight = xHeight * (DESIGN_CAP / DESIGN_X)): StrokeGlyph | null {
  const key = SAME_AS[unit] ?? unit;
  const def = DEFS[key];
  if (!def) return null;
  const kx = Math.max(0.3, Math.min(1.4, xHeight / DESIGN_X));
  const kc = Math.max(kx, Math.min(kx * 2.2, (capHeight - xHeight) / (DESIGN_CAP - DESIGN_X)));
  const id = `${key}@${kx.toFixed(3)}:${kc.toFixed(3)}`;
  let glyph = cache.get(id);
  if (glyph === undefined) {
    const strokes = parseStrokes(def.d);
    let reach = 0;
    for (const stroke of strokes) {
      for (let i = 0; i < stroke.length; i += 3) {
        const y = stroke[i + 1];
        stroke[i + 1] = y < -DESIGN_X ? -DESIGN_X * kx + (y + DESIGN_X) * kc : y * kx;
        reach = Math.min(reach, y);
      }
    }
    // A glyph as tall as a capital is widened a little with it, or it looks pinched.
    const kw = reach < -DESIGN_X - 0.05 ? (kx + kc) / 2 : kx;
    for (const stroke of strokes) for (let i = 0; i < stroke.length; i += 3) stroke[i] *= kw;
    glyph = { strokes, advance: def.w * kw };
    cache.set(id, glyph);
  }
  return glyph;
}

/** Every character with a pen-drawn glyph, for tests and the symbol sheet. */
export function symbolCharacters(): string[] {
  return Object.keys(DEFS);
}

/**
 * Turn a path string into strokes of x, y, pressure triples, flattening each
 * curve into short straight steps. Pressure eases in and out along a stroke,
 * the way it does when a pen is put down and lifted.
 */
export function parseStrokes(d: string, k = 1): Float32Array[] {
  const tokens = d.match(/[MLQC]|-?\d*\.?\d+(?:e-?\d+)?/g) ?? [];
  const strokes: number[][] = [];
  let current: number[] | null = null;
  let x = 0;
  let y = 0;
  let i = 0;
  const num = () => Number(tokens[i++]) * k;
  const push = (px: number, py: number) => {
    current!.push(px, py, 1);
  };
  while (i < tokens.length) {
    const op = tokens[i++];
    if (op === 'M') {
      x = num();
      y = num();
      current = [];
      strokes.push(current);
      push(x, y);
    } else if (op === 'L') {
      // Straight runs are cut into short steps so that smoothing the stroke
      // later rounds off only the very tip of a corner, not the whole side.
      const ex = num();
      const ey = num();
      const steps = Math.max(1, Math.ceil(Math.hypot(ex - x, ey - y) / (0.035 * k)));
      for (let s = 1; s <= steps; s++) push(x + ((ex - x) * s) / steps, y + ((ey - y) * s) / steps);
      x = ex;
      y = ey;
    } else if (op === 'Q') {
      const cx = num();
      const cy = num();
      const ex = num();
      const ey = num();
      for (let s = 1; s <= 8; s++) {
        const t = s / 8;
        const a = (1 - t) * (1 - t);
        const b = 2 * (1 - t) * t;
        const c = t * t;
        push(a * x + b * cx + c * ex, a * y + b * cy + c * ey);
      }
      x = ex;
      y = ey;
    } else if (op === 'C') {
      const c1x = num();
      const c1y = num();
      const c2x = num();
      const c2y = num();
      const ex = num();
      const ey = num();
      for (let s = 1; s <= 10; s++) {
        const t = s / 10;
        const a = (1 - t) ** 3;
        const b = 3 * (1 - t) ** 2 * t;
        const c = 3 * (1 - t) * t * t;
        const e = t ** 3;
        push(a * x + b * c1x + c * c2x + e * ex, a * y + b * c1y + c * c2y + e * ey);
      }
      x = ex;
      y = ey;
    } else {
      // A stray number: skip it rather than lose the whole glyph.
      if (current === null) break;
    }
  }
  return strokes.filter((s) => s.length >= 3).map((s) => easePressure(Float32Array.from(s)));
}

function easePressure(stroke: Float32Array): Float32Array {
  const n = stroke.length / 3;
  if (n < 3) return stroke;
  for (let i = 0; i < n; i++) {
    const t = i / (n - 1);
    stroke[i * 3 + 2] = 0.75 + 0.25 * Math.sin(Math.PI * Math.min(1, t * 1.15));
  }
  return stroke;
}
